"""Build shoes.js from the sourced data in data/*.json.

Each data file holds, per shoe, every field as {"value", "quote", "source"} taken from the
manufacturer's own website; null values mean the manufacturer does not state it.
Non-EUR list prices are converted with the ECB reference rates below.

Run: uv run scripts/build.py
"""

import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"

# ECB euro reference rates (units per EUR).
RATES_DATE = "2026-11-04"
RATES = {"EUR": 1.0, "USD": 1.1267, "GBP": 0.83460, "CZK": 24.309, "CHF": 0.9188}
SYMBOL = {"USD": "$", "GBP": "£", "CHF": "CHF ", "CZK": "CZK "}

BRAND_ORDER = [
    "La Sportiva", "Scarpa", "Tenaya", "Ocun", "Five Ten", "Black Diamond", "Boreal", "Evolv",
    "Butora", "Mad Rock", "Unparallel", "So iLL", "Red Chili", "Wild Climb", "Simond", "Triop", "Saltic",
]
USES = {"bouldering", "sport", "trad", "multipitch", "crack", "slab", "gym", "competition",
        "all-round", "beginner", "vegan"}
ENUMS = {
    "gender": {"U", "MW", "M", "W"}, "closure": {"L", "V", "S"},
    "width": {"N", "M", "W"}, "volume": {"L", "M", "H"},
}
RANGES = {"asymmetry": (0, 3), "downturn": (0, 3), "stiffness": (1, 5)}

HEADER = """// Climbing shoe dataset. GENERATED by scripts/build.py from data/*.json; edit those, not this file.
// Every value comes from the manufacturer's own website (quote and source URL in data/*.json).
// null = the manufacturer does not state it.
//
// Row format:
// [brand, model, gender, closure, width, volume, asymmetry, downturn, stiffness, rubber, uses, priceEUR, url, priceOriginal]
//   gender:    U = unisex, MW = separate men's and women's versions, M = men's, W = women's
//   closure:   L = lace, V = velcro / strap, S = slipper
//   width:     N = narrow, M = medium, W = wide
//   volume:    L = low, M = standard, H = high
//   asymmetry: 0 none, 1 slight, 2 moderate, 3 strong
//   downturn:  0 flat, 1 slight, 2 moderate, 3 aggressive
//   stiffness: 1 very soft .. 5 very stiff
//   uses:      space-separated tags
//   price:     official list price in EUR; converted with ECB rates of {rates_date} when the
//              brand lists another currency, then priceOriginal holds that price (e.g. "$169")
//   url:       official product page
"""


def val(shoe, key, errors):
    f = shoe.get(key) or {}
    v = f.get("value")
    if v is None:
        return None
    if not f.get("source"):
        errors.append(f"{shoe['brand']} {shoe['model']}: {key} has a value but no source")
    return v


def row(shoe, errors):
    name = f"{shoe['brand']} {shoe['model']}"
    out = {k: val(shoe, k, errors) for k in
           ["gender", "closure", "width", "volume", "asymmetry", "downturn", "stiffness", "rubber", "uses", "price"]}
    for k, allowed in ENUMS.items():
        if out[k] is not None and out[k] not in allowed:
            errors.append(f"{name}: bad {k} {out[k]!r}")
    for k, (lo, hi) in RANGES.items():
        v = out[k]
        if v is not None and not (isinstance(v, int) and lo <= v <= hi):
            errors.append(f"{name}: bad {k} {v!r}")
    uses = out["uses"]
    if uses is not None:
        bad = set(uses) - USES
        if bad:
            errors.append(f"{name}: unknown uses {sorted(bad)}")
        uses = " ".join(u for u in uses if u in USES) or None
    price = orig = None
    if out["price"] is not None:
        amount, cur = out["price"]["amount"], out["price"]["currency"]
        if cur not in RATES:
            errors.append(f"{name}: no rate for {cur}")
        else:
            price = round(amount / RATES[cur])
            if cur != "EUR":
                orig = f"{SYMBOL[cur]}{amount:g}"
    return [shoe["brand"], shoe["model"], out["gender"], out["closure"], out["width"], out["volume"],
            out["asymmetry"], out["downturn"], out["stiffness"], out["rubber"], uses, price, shoe.get("url"), orig]


def main():
    shoes = [s for p in sorted(DATA.glob("*.json")) for s in json.loads(p.read_text())]
    unknown = {s["brand"] for s in shoes} - set(BRAND_ORDER)
    if unknown:
        sys.exit(f"brands missing from BRAND_ORDER: {sorted(unknown)}")
    errors = []
    rows = [row(s, errors) for b in BRAND_ORDER for s in shoes if s["brand"] == b]
    if errors:
        sys.exit("\n".join(errors))
    lines = [HEADER.format(rates_date=RATES_DATE), f'window.SHOES_UPDATED = "{date.today().isoformat()}";',
             "window.SHOES_RAW = ["]
    brand = None
    for r in rows:
        if r[0] != brand:
            if brand:
                lines.append("")
            lines.append(f"  // {r[0]}")
            brand = r[0]
        lines.append("  " + json.dumps(r, ensure_ascii=False, separators=(",", ":")) + ",")
    lines.append("];\n")
    (ROOT / "shoes.js").write_text("\n".join(lines))
    print(f"wrote {len(rows)} shoes")


if __name__ == "__main__":
    main()
